import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

FEATURES = [
    "title_levenshtein", "title_token_sort", "title_token_set",
    "title_jaccard", "title_exact", "title_len_diff_ratio",
    "author_jaccard", "author_first_match", "author_any_match",
    "year_diff", "year_exact", "year_missing", "cite_count",
]
META = ["arxiv_id", "citation_key", "ref_arxiv_id", "groundtruth_arxiv_id", "label"]
QUERY_KEYS = ["arxiv_id", "citation_key"]
EXPECTED_TRAIN_SHA = "f9cf5eb22ad1aad07b2db3135c26802cf00cd06fffc9e183dbaa3275c7dec27f"
EXPECTED_VALID_SHA = "f62896841d6f3b5ebbc38ea098873eaa4daacaa34a22d5c4efc7c5cde49fd294"
EXPECTED_TRAIN_ROWS = 4_185_238
EXPECTED_VALID_ROWS = 4_261
EXPECTED_QUERIES = 53
EXPECTED_POSITIVE_QUERIES = 38
EXPECTED_NULL_QUERIES = 15
EXPECTED_MRR = 38 / 53
EXPECTED_GITHUB_COMMIT = "7f542abd88f4864b58bbca3fe183a0a4b7e7628b"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(4 * 1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def git_blob_sha(path: Path) -> str:
    content = path.read_bytes()
    return hashlib.sha1(f"blob {len(content)}\0".encode() + content).hexdigest()


def checked(condition: Any, what: str) -> None:
    if not condition:
        raise AssertionError(what)
    print(f"[PASS] {what}")


def restricted_input(value: str, basename: str) -> Path:
    path = Path(value).expanduser().resolve()
    checked(path.is_file(), f"File exists: {path}")
    checked(path.name.lower() == basename, f"Only {basename} is allowed")
    return path


def load_json(path: Path) -> dict:
    checked(path.is_file(), f"Artifact exists: {path}")
    return json.loads(path.read_text(encoding="utf-8-sig"))


def feature_and_data_checks(frame: pd.DataFrame) -> tuple[int, int]:
    checked(len(frame) == EXPECTED_VALID_ROWS, f"Validation row count = {EXPECTED_VALID_ROWS}")
    checked(len(frame.columns) == len(FEATURES + META), "13 features + 5 meta columns loaded")
    checked(frame[FEATURES].notna().all().all(), "No missing feature values")
    checked(np.isfinite(frame[FEATURES].to_numpy(dtype=np.float64)).all(), "Features finite")
    checked(frame["label"].isin([0, 1]).all(), "Labels only 0/1")
    checked(frame[QUERY_KEYS + ["ref_arxiv_id"]].notna().all().all(), "No null query/candidate keys")
    checked(not frame.duplicated(QUERY_KEYS + ["ref_arxiv_id"]).any(), "No duplicate candidate in a query")
    positives = 0
    nulls = 0
    for query, group in frame.groupby(QUERY_KEYS, sort=True):
        checked(group["groundtruth_arxiv_id"].nunique(dropna=False) == 1,
                f"One groundtruth value per query {query}")
        gt = group["groundtruth_arxiv_id"].iloc[0]
        mask = (group["ref_arxiv_id"] == gt) if pd.notna(gt) else pd.Series(False, index=group.index)
        checked(np.array_equal(mask.to_numpy(dtype=np.int8), group["label"].to_numpy(dtype=np.int8)),
                f"Label consistent with selected GT for {query}")
        if group["label"].eq(1).any():
            positives += 1
        else:
            checked(pd.isna(gt), f"Query without positive must be GT-null: {query}")
            nulls += 1
    checked(positives + nulls == EXPECTED_QUERIES, "Validation query count = 53")
    checked((positives, nulls) == (EXPECTED_POSITIVE_QUERIES, EXPECTED_NULL_QUERIES),
            "38 positives + 15 GT-null queries")
    return positives, nulls


def verify_lr(blob: dict, full_metrics: dict) -> Pipeline:
    checked(isinstance(blob, dict) and set(["features", "pipeline"]).issubset(blob),
            "LR13 artifact has pipeline + feature list")
    checked(blob["features"] == FEATURES, "LR13 feature names and order exactly frozen")
    pipe = blob["pipeline"]
    checked(isinstance(pipe, Pipeline), "LR13 uses sklearn Pipeline")
    checked(list(pipe.named_steps) == ["standardscaler", "logisticregression"],
            "LR13 Pipeline is StandardScaler -> LogisticRegression")
    scaler, lr = pipe.named_steps["standardscaler"], pipe.named_steps["logisticregression"]
    checked(isinstance(scaler, StandardScaler) and isinstance(lr, LogisticRegression),
            "LR13 estimator types verified")
    checked(lr.solver == "lbfgs" and lr.max_iter == 1000 and lr.class_weight is None,
            "LR13 solver/max_iter/class_weight frozen")
    checked(int(np.asarray(lr.n_iter_).max()) == full_metrics["model"]["n_iter"],
            "LR13 iterations match FULL metrics")
    seen = np.asarray(scaler.n_samples_seen_)
    checked(np.all(seen == EXPECTED_TRAIN_ROWS), "LR13 scaler fitted on full 4,185,238 Train pairs")
    checked(int(lr.n_features_in_) == 13, "LR13 fitted with 13 columns")
    checked(np.array_equal(lr.classes_, [0, 1]), "LR13 binary classes [0,1]")
    checked(np.isclose(lr.intercept_[0], full_metrics["model"]["intercept"], rtol=1e-9, atol=1e-10),
            "LR13 intercept matches published metrics")
    return pipe


def verify_lgbm(blob: dict, full_metrics: dict):
    checked(isinstance(blob, dict) and set(["features", "model"]).issubset(blob),
            "LGBM13 artifact has model + feature list")
    checked(blob["features"] == FEATURES, "LGBM13 feature names and order exactly frozen")
    from lightgbm import LGBMClassifier
    model = blob["model"]
    checked(isinstance(model, LGBMClassifier), "LGBM13 uses LGBMClassifier")
    checked(int(model.n_estimators_) == full_metrics["model"]["actual_trees"] == 300,
            "LGBM13 300 actual trees match FULL metrics")
    checked(model.get_params()["n_estimators"] == 300 and model.get_params()["random_state"] == 42,
            "LGBM13 n_estimators=300, random_state=42")
    checked(np.array_equal(model.classes_, [0, 1]), "LGBM13 binary classes [0,1]")
    checked(list(model.booster_.feature_name()) == FEATURES, "LGBM13 booster feature order matches 13 features")
    return model


def ranking_with_scores(frame: pd.DataFrame, proba: np.ndarray) -> tuple[list[dict[str, Any]], dict[str, float]]:
    checked(len(proba) == len(frame), "Scoring covers every validation pair")
    checked(np.isfinite(proba).all() and np.all((proba >= 0) & (proba <= 1)),
            "All positive-class scores finite and in [0,1]")
    scored = frame.copy()
    scored["score"] = proba
    allrows = []
    q_rr = []
    pos_rr = []
    for key, group in scored.groupby(QUERY_KEYS, sort=True):
        ordered = group.assign(_tie_order=np.arange(len(group))).sort_values(
            ["score", "_tie_order"], ascending=[False, True], kind="mergesort"
        )
        positions = np.flatnonzero(ordered["label"].to_numpy(dtype=int) == 1)
        rank_pos = (int(positions[0]) + 1) if len(positions) else None
        rr = 1.0 / rank_pos if rank_pos is not None and rank_pos <= 5 else 0.0
        q_rr.append(rr)
        if rank_pos is not None:
            pos_rr.append(rr)
        for rank, (_, row) in enumerate(ordered.head(5).iterrows(), start=1):
            allrows.append({"arxiv_id": str(key[0]), "citation_key": str(key[1]),
                            "rank": rank, "ref_arxiv_id": str(row["ref_arxiv_id"]),
                            "score": float(row["score"]), "label": int(row["label"])})
    metrics = {"queries": len(q_rr), "positive_queries": len(pos_rr),
               "mrr_at_5": float(math.fsum(q_rr) / len(q_rr)),
               "mrr_at_5_positive_only": float(math.fsum(pos_rr) / len(pos_rr))}
    return allrows, metrics


def compare_saved_top5(rows: list[dict], saved_csv: Path, model_name: str) -> None:
    checked(saved_csv.is_file(), f"Published {model_name} validation_top5.csv exists")
    with saved_csv.open(encoding="utf-8-sig", newline="") as f:
        published = list(csv.DictReader(f))
    checked(len(rows) == len(published) == 265, f"{model_name}: 53xTop5=265 rows")
    for i, (actual, expected) in enumerate(zip(rows, published), 1):
        for k in ["arxiv_id", "citation_key", "ref_arxiv_id"]:
            if str(actual[k]) != str(expected[k]):
                raise AssertionError(f"{model_name}: row {i} {k}: {actual[k]!r} != {expected[k]!r}")
        for k in ["rank", "label"]:
            if int(actual[k]) != int(expected[k]):
                raise AssertionError(f"{model_name}: row {i} {k}: {actual[k]} != {expected[k]}")
        if not np.isclose(actual["score"], float(expected["score"]), rtol=1e-5, atol=1e-9):
            raise AssertionError(f"{model_name}: row {i} score mismatch")
    print(f"[PASS] {model_name} score/order/label match all 265 published Top-5 rows")


def synthetic_tiebreak_and_topk() -> None:
    # Isolated sorting contract tests: 1, 3, 5, 6 candidates and score ties.
    for n in [1, 3, 5, 6]:
        group = pd.DataFrame({"ref_arxiv_id": [f"r{i}" for i in range(n)], "score": [0.5] * n})
        sorted_group = group.assign(_tie_order=np.arange(len(group))).sort_values(
            ["score", "_tie_order"], ascending=[False, True], kind="mergesort"
        )
        observed = sorted_group.head(5)["ref_arxiv_id"].tolist()
        assert observed == [f"r{i}" for i in range(min(n, 5))]
    print("[PASS] Synthetic stable ties and 1/3/5/6-candidate Top-5 contracts")


def load_model(path: Path):
    checked(path.is_file(), f"Local trusted model file exists: {path}")
    # SECURITY: pickle-based joblib must NEVER be loaded from untrusted sources.
    return joblib.load(path)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--repo", type=Path, default=Path("."))
    ap.add_argument("--train", required=True, type=str)
    ap.add_argument("--valid", required=True, type=str)
    ap.add_argument("--protocol", type=Path, required=True)
    ap.add_argument("--out-dir", required=True, type=Path)
    args = ap.parse_args()
    try:
        repo = args.repo.resolve()
        checked(repo.is_dir(), "Repository directory exists")
        out = args.out_dir.resolve()
        checked(not out.exists(), "Output directory is NEW; no overwrite")
        train = restricted_input(args.train, "train_pairs.parquet")
        valid = restricted_input(args.valid, "valid_pairs.parquet")
        checked(train != valid, "Train and Validation are different files")
        checked(sha256(train) == EXPECTED_TRAIN_SHA, "Frozen Train SHA256 matches M3 Range1 2026-11-23")
        checked(sha256(valid) == EXPECTED_VALID_SHA, "Frozen Valid SHA256 matches M3 Range1 2026-11-23")

        protocol_file = args.protocol.resolve()
        protocol = load_json(protocol_file)
        checked(protocol["github"]["commit_sha"] == EXPECTED_GITHUB_COMMIT,
                "Manifest pins the checked Git commit")
        checked(protocol["selected_model"]["name"] == "LR13", "Primary selected model is LR13")
        checked(protocol["features"] == FEATURES, "Manifest has exact ordered 13 features")
        checked(protocol["validation_r1"]["sha256"] == EXPECTED_VALID_SHA,
                "Manifest specifies the correct Valid checksum")
        checked(protocol["training_r1"]["sha256"] == EXPECTED_TRAIN_SHA,
                "Manifest specifies the correct Train checksum")
        checked(protocol["scoring"]["tie_break"] == "candidate_original_row_order",
                "Stable tie-break pinned in manifest")
        checked(protocol["evaluation"]["gt_null_rr"] == 0,
                "GT-null RR=0 protocol is pinned")

        for rel, sha in protocol["github"]["source_git_blob_shas"].items():
            src = repo / rel
            checked(src.exists(), f"Source code exists: {rel}")
            actual = git_blob_sha(src)
            # On Windows checkout may use CRLF; normalize CRLF for Git blob comparison.
            if actual != sha and b"\r\n" in src.read_bytes():
                content = src.read_bytes().replace(b"\r\n", b"\n")
                actual = hashlib.sha1(f"blob {len(content)}\0".encode() + content).hexdigest()
            checked(actual == sha, f"Source file matches pinned Git blob: {rel}")

        import pyarrow.parquet as pq
        tr = pq.ParquetFile(train)
        va = pq.ParquetFile(valid)
        checked(tr.metadata.num_rows == EXPECTED_TRAIN_ROWS, "Train Parquet row count matches")
        checked(va.metadata.num_rows == EXPECTED_VALID_ROWS, "Valid Parquet row count matches")
        checked(set(FEATURES + ["label"]).issubset(tr.schema_arrow.names), "Train columns exist")
        checked(set(FEATURES + META).issubset(va.schema_arrow.names), "Valid columns exist")
        data = pd.read_parquet(valid, columns=FEATURES + META)
        pos_count, null_count = feature_and_data_checks(data)
        synthetic_tiebreak_and_topk()

        reports = {}
        for name, artifact_rel, key in [
            ("LR13", "outputs/lr13_full_20261125_01/lr13_model.joblib", "pipeline"),
            ("LGBM13", "outputs/lgbm13_full_20261125_01/lgbm13_model.joblib", "model"),
        ]:
            model_file = repo / artifact_rel
            metrics_file = model_file.parent / "metrics.json"
            metrics = load_json(metrics_file)
            checked(metrics.get("run_type") == "FULL_TRAINING", f"{name}: FULL_TRAINING run")
            checked(metrics["data"]["train"]["sha256"] == EXPECTED_TRAIN_SHA,
                    f"{name}: metadata Train hash matches")
            checked(metrics["data"]["valid"]["sha256"] == EXPECTED_VALID_SHA,
                    f"{name}: metadata Valid hash matches")
            checked(metrics["features"] == FEATURES, f"{name}: metrics feature order matches")
            checked(metrics["train"]["pairs"] == EXPECTED_TRAIN_ROWS,
                    f"{name}: metadata Training rows matches")
            blob = load_model(model_file)
            if name == "LR13":
                model = verify_lr(blob, metrics)
                X = data[FEATURES].to_numpy(dtype=np.float64, copy=True)
                proba = model.predict_proba(X)[:, 1]
            else:
                model = verify_lgbm(blob, metrics)
                X = data[FEATURES].to_numpy(dtype=np.float32, copy=True)
                proba = model.predict_proba(pd.DataFrame(X, columns=FEATURES))[:, 1]
            rows, eval_report = ranking_with_scores(data, proba)
            checked(np.isclose(eval_report["mrr_at_5"], EXPECTED_MRR, atol=1e-12),
                    f"{name}: MRR@5 agrees with 38/53")
            checked(np.isclose(eval_report["mrr_at_5_positive_only"], 1.0, atol=1e-12),
                    f"{name}: Positive-only MRR@5=1.0")
            compare_saved_top5(rows, model_file.parent / "validation_top5.csv", name)
            reports[name] = {"model_file": str(model_file), "model_sha256": sha256(model_file),
                             "metrics_file_sha256": sha256(metrics_file),
                             "validation": eval_report, "top5_rows_verified": len(rows)}

        report = {"result": "PASS", "scope": "Range1 Train + Range1 Validation only; Test unopened",
                  "commit_reference": EXPECTED_GITHUB_COMMIT,
                  "source_protocol_sha256": sha256(protocol_file),
                  "train_sha256": EXPECTED_TRAIN_SHA,
                  "valid_sha256": EXPECTED_VALID_SHA,
                  "validation_positive_queries": pos_count, "validation_gt_null_queries": null_count,
                  "models": reports}
        verified_lock = dict(protocol)
        verified_lock["status"] = "VERIFIED_LOCAL_PREFLIGHT_NO_TEST__READY_FOR_USER_REVIEW"
        verified_lock["selected_model"]["model_sha256"] = reports["LR13"]["model_sha256"]
        verified_lock["selected_model"]["artifact_status"] = "VERIFIED_LOCAL"
        for cmp in verified_lock["comparators"]:
            if cmp.get("name") == "LGBM13":
                cmp["model_sha256"] = reports["LGBM13"]["model_sha256"]
                cmp["status"] = "VERIFIED_LOCAL_FROZEN_COMPARATOR"
        verified_lock["pending_gates"] = [
            "Review & accept primary-model choice before the one-time Test run",
            "Cross-range Train R1 vs external Valid/Test overlap must be audited before strong independent generalization claims"
        ]
        verified_lock["verification"] = report
        out.mkdir(parents=True, exist_ok=False)
        (out / "verification_report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
        (out / "verified_protocol_lock.json").write_text(json.dumps(verified_lock, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"\n=== SUCCESS: LOCAL PREFLIGHT PASSED ===\nSaved: {out / 'verified_protocol_lock.json'}")
        print("NO Test opened. No training/relabeling/mutation performed.")
        return 0
    except (OSError, ValueError, KeyError, AssertionError, ImportError, AttributeError, TypeError) as exc:
        print(f"\n[FAILED; NO LOCK CREATED] {type(exc).__name__}: {exc}", file=sys.stderr)
        print("Do not open Test until this check is resolved and protocol is locked.", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
